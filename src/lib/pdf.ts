import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { formatDuration, minutesToHours } from './datetime';
import type { ReportData } from '@/hooks/useReports';

export interface PdfOptions {
  companyName: string;
  logoUrl?: string | null;
  period: string;
  report: ReportData;
  employeeFilter?: string;
}

export async function generateTimesheetPdf(opts: PdfOptions): Promise<void> {
  const doc = new jsPDF();
  const { companyName, period, report } = opts;
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(companyName, 14, 22);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text('Time & Hours Report', 14, 29);
  doc.text(period, 14, 35);

  doc.setDrawColor(200);
  doc.line(14, 39, pageWidth - 14, 39);

  // Summary stats
  let y = 47;
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(0);
  doc.text('Summary', 14, y);
  y += 8;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  const stats = [
    ['Total hours', formatDuration(report.totalMinutes)],
    ['Regular hours', formatDuration(report.regularMinutes)],
    ['Overtime hours', formatDuration(report.overtimeMinutes)],
    ['Break hours', formatDuration(report.breakMinutes)],
    ['Missing clock-outs', String(report.missingClockOuts)],
  ];
  for (const [label, value] of stats as [string, string][]) {
    doc.setTextColor(100);
    doc.text(label, 14, y);
    doc.setTextColor(0);
    doc.setFont('helvetica', 'bold');
    doc.text(value, 80, y);
    doc.setFont('helvetica', 'normal');
    y += 6;
  }

  // Hours by employee table
  if (report.byEmployee.length > 0) {
    y += 6;
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(0);
    doc.text('Hours by Employee', 14, y);
    y += 2;

    autoTable(doc, {
      startY: y,
      head: [['Employee', 'Regular', 'Overtime', 'Breaks', 'Total']],
      body: report.byEmployee.map((r) => [
        r.name,
        `${minutesToHours(r.regularMinutes)}h`,
        `${minutesToHours(r.overtimeMinutes)}h`,
        `${minutesToHours(r.breakMinutes)}h`,
        `${minutesToHours(r.totalMinutes)}h`,
      ]),
      theme: 'grid',
      headStyles: { fillColor: [30, 41, 59], fontSize: 8 },
      bodyStyles: { fontSize: 8 },
      columnStyles: {
        1: { halign: 'right' },
        2: { halign: 'right' },
        3: { halign: 'right' },
        4: { halign: 'right', fontStyle: 'bold' },
      },
      margin: { left: 14, right: 14 },
    });

    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10;
  }

  // Hours by job site
  if (report.byJobSite.length > 0) {
    if (y > 240) {
      doc.addPage();
      y = 20;
    }

    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(0);
    doc.text('Hours by Job Site', 14, y);
    y += 2;

    autoTable(doc, {
      startY: y,
      head: [['Job Site', 'Actual Hours', 'Estimated Hours']],
      body: report.byJobSite.map((r) => [
        r.name,
        `${minutesToHours(r.actualMinutes)}h`,
        r.estimatedHours != null ? `${r.estimatedHours}h` : '—',
      ]),
      theme: 'grid',
      headStyles: { fillColor: [30, 41, 59], fontSize: 8 },
      bodyStyles: { fontSize: 8 },
      columnStyles: {
        1: { halign: 'right' },
        2: { halign: 'right' },
      },
      margin: { left: 14, right: 14 },
    });

    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10;
  }

  // Daily breakdown
  if (report.daily.length > 0) {
    if (y > 220) {
      doc.addPage();
      y = 20;
    }

    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(0);
    doc.text('Daily Breakdown', 14, y);
    y += 2;

    autoTable(doc, {
      startY: y,
      head: [['Date', 'Hours']],
      body: report.daily.map((r) => [
        r.dateKey,
        `${minutesToHours(r.minutes)}h`,
      ]),
      theme: 'grid',
      headStyles: { fillColor: [30, 41, 59], fontSize: 8 },
      bodyStyles: { fontSize: 8 },
      columnStyles: { 1: { halign: 'right' } },
      margin: { left: 14, right: 14 },
    });
  }

  // Footer on all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(7);
    doc.setTextColor(150);
    doc.text(
      `Generated by VoltTrack · Page ${i} of ${totalPages}`,
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 8,
      { align: 'center' },
    );
  }

  doc.save(`volttrack-report_${opts.period.replace(/\s/g, '_')}.pdf`);
}
